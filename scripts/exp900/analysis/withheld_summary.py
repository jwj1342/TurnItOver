"""Summarize the withheld-evidence evaluation against the original full-observation predictions.

Per model, supervision and seed, per tier and overall, on the withheld cases:
  uncertain  = share of cases whose predicted verdict status is uncertain
  reports withheld gold = share of cases where a predicted finding names a gold defect_id of the case although every
                          cell exposing it was withheld (hallucinated recall)
  any finding = share of cases with at least one predicted finding
  invalid     = share of cases her parser rejected (e.g. citing a step that does not exist); statuses and findings are
                taken from a lenient JSON parse of the raw output so rejected outputs still count
The same three rates on the original full-observation predictions restricted to the same case ids are shown for
comparison. Usage: python analysis/withheld_summary.py  (writes out/RESULTS-withheld.md)
"""
from __future__ import annotations
import os
import json, re
from collections import defaultdict
from pathlib import Path
TIO = Path(os.environ.get('TIO_RUNS', '/scratch/jwj/tio-runs'))
WITHHELD = TIO / 'data900/three-tier-900-withheld-v1/episode_export'
SRC = TIO / 'data900/three-tier-900-sft-v1/episode_export'
TIERS = ('easy', 'medium', 'hard', 'all')
ORDER = {'zero-shot': 0, 'ordinary': 1, 'evidence': 2}


def rows(path: Path) -> list[dict]:
    return [json.loads(l) for l in path.read_text().splitlines() if l.strip()]


def lenient(raw: str):
    text = (raw or '').strip()
    if text.startswith('```json') and text.endswith('```'):
        text = text[7:-3].strip()
    try:
        v = json.loads(text)
        verdict = v['verdict']
        return verdict.get('status'), [f.get('defect_id') for f in verdict.get('findings', []) if isinstance(f, dict)]
    except Exception:
        return None, []


def discover_withheld():
    runs = {}
    for m in sorted(TIO.glob('out/withheld-*/*/*-withheld/predictions.jsonl')):
        size = m.parts[-3]; leaf = m.parts[-2]
        if leaf == 'base-withheld':
            key = (size, 'zero-shot', '-')
        else:
            seed, sup, _ = leaf.split('-'); key = (size, sup, seed[4:])
        runs[key] = m
    return runs


def discover_full():
    runs = {}
    for m in sorted(TIO.glob('out/level900-sft-*/*/seed*/*-diagnosis/eval-validation/predictions.jsonl')):
        runs[(m.parts[-5], m.parts[-3].split('-')[0], m.parts[-4][4:])] = m
    for m in sorted(TIO.glob('out/level900-base-*/*/base-validation/predictions.jsonl')):
        runs[(m.parts[-3], 'zero-shot', '-')] = m
    return runs


def rates(preds, ids, gold, tier):
    acc = defaultdict(lambda: defaultdict(list))
    for r in preds:
        cid = r['episode_id']
        if cid not in ids:
            continue
        status, defects = lenient(r.get('raw'))
        if r.get('valid') and r.get('predicted_status'):
            status = r['predicted_status']
            defects = [f[0] for f in r.get('predicted_findings') or []] or defects
        for t in (tier[cid], 'all'):
            a = acc[t]
            a['uncertain'].append(status == 'uncertain'); a['fail'].append(status == 'fail')
            a['halluc'].append(bool(set(defects) & gold[cid])); a['any'].append(bool(defects))
            a['invalid'].append(not r.get('valid')); a['n'].append(1)
    return {t: {k: (100 * sum(v) / len(v) if k != 'n' else len(v)) for k, v in a.items()} for t, a in acc.items()}


def fmt_seeds(vals):
    vals = [v for v in vals if v is not None]
    if not vals:
        return '–'
    if len(vals) == 1:
        return f'{vals[0]:.1f}'
    return f'{sum(vals)/len(vals):.1f} [{min(vals):.1f}, {max(vals):.1f}]'


def main() -> None:
    kept = rows(WITHHELD / 'validation.episodes.jsonl')
    ids = {r['episode_id'] for r in kept}; tier = {r['episode_id']: r['difficulty'] for r in kept}
    gold = {a['id']: {lab['defect_id'] for lab in a['labels']} for a in rows(WITHHELD / 'annotations.private.jsonl')}
    wh, full = discover_withheld(), discover_full()
    per = {}
    for key, path in wh.items():
        per[key] = {'withheld': rates(rows(path), ids, gold, tier),
                    'full': rates(rows(full[key]), ids, gold, tier) if key in full else {}}
    groups = defaultdict(list)
    for key, v in per.items():
        groups[(key[0], key[1])].append(v)
    lines = [f'# Withheld-evidence evaluation ({len(ids)} defective validation cases; every exposing cell removed)', '',
             f'Runs: {len(per)} withheld, generated by analysis/withheld_summary.py. Values are %, mean [min, max] over seeds. "full" = the original fixed full-observation predictions on the same cases.', '']
    for metric, title in (('uncertain', 'Uncertain verdict rate'), ('halluc', 'Reports a withheld gold defect (hallucinated recall)'), ('any', 'Any finding'), ('invalid', 'Rejected by her parser (invalid output)')):
        lines += [f'## {title}', '', '| Model | Supervision | ' + ' | '.join(f'{t} withheld | {t} full' for t in TIERS) + ' |', '|---|---|' + '---:|' * (2 * len(TIERS))]
        for size, sup in sorted(groups, key=lambda k: (k[0], ORDER[k[1]])):
            cells = []
            for t in TIERS:
                cells.append(fmt_seeds([g['withheld'].get(t, {}).get(metric) for g in groups[(size, sup)]]))
                cells.append(fmt_seeds([g['full'].get(t, {}).get(metric) for g in groups[(size, sup)]]))
            lines.append(f'| Qwen3-VL-{size} | {sup} | ' + ' | '.join(cells) + ' |')
        lines.append('')
    n = defaultdict(int)
    for cid in ids:
        n[tier[cid]] += 1
    lines += ['## Notes', '', f'- Cases per tier: {dict(n)}. The first reference image is always shown; for Easy the remaining cell is the rest pair, which is pixel-identical to the reference for kinematic defects.',
              '- Statuses and defect ids come from her parsed row when the output was valid, otherwise from a lenient JSON parse of the raw text, so outputs rejected only for citing a step that no longer exists still count as findings.',
              '- "reports a withheld gold defect" is the share of cases, not findings. Mislabeled findings on withheld cases show up in "any finding" but not here.']
    (TIO / 'out/RESULTS-withheld.md').write_text('\n'.join(lines) + '\n')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
